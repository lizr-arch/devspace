import assert from "node:assert/strict";
import { mkdtempSync, rmSync, mkdirSync, symlinkSync, chmodSync, statSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import Database from "better-sqlite3";
import { CoachReviewEventStore } from "./coach-review-events.js";
const root = mkdtempSync(join(tmpdir(),"coach-native-event-test-"));
const state = join(root,"state");
const hash="a".repeat(64);
const hash2="b".repeat(64);
try {
 const store=new CoachReviewEventStore(state);
 const e=store.recordCompleted({workspaceId:"ws-a",operationId:"codex-1",evidenceSha256:hash});
 assert.equal(e.event_id,1);
 assert.equal(store.recordCompleted({workspaceId:"ws-a",operationId:"codex-1",evidenceSha256:hash}).event_id,1);
 assert.throws(()=>store.recordCompleted({workspaceId:"ws-a",operationId:"codex-1",evidenceSha256:hash2}),/CONFLICT/);
 const e2=store.recordCompleted({workspaceId:"ws-b",operationId:"codex-1",evidenceSha256:hash2});
 assert.notEqual(e.event_id,e2.event_id);
 assert.equal(store.listPending("ws-a").pending_count,1);
 assert.equal(store.listPending("ws-b").pending_count,1);
 assert.throws(()=>store.submitReview({workspaceId:"ws-b",eventId:e.event_id,decision:"APPROVED",evidenceSha256:hash}),/MISMATCH/);
 assert.throws(()=>store.submitReview({workspaceId:"ws-a",eventId:e.event_id,decision:"APPROVED",evidenceSha256:hash2}),/MISMATCH/);
 const receipt=store.submitReview({workspaceId:"ws-a",eventId:e.event_id,decision:"APPROVED",evidenceSha256:hash});
 assert.equal(receipt.decision,"APPROVED");
 assert.equal(store.submitReview({workspaceId:"ws-a",eventId:e.event_id,decision:"APPROVED",evidenceSha256:hash}).reviewed_at,receipt.reviewed_at);
 assert.throws(()=>store.submitReview({workspaceId:"ws-a",eventId:e.event_id,decision:"REWORK",evidenceSha256:hash}),/CONFLICT/);
 assert.equal(store.listPending("ws-a").pending_count,0);
 assert.equal(store.listPending("ws-b").pending_count,1);
 assert.throws(()=>store.recordCompleted({workspaceId:"../outside",operationId:"x",evidenceSha256:hash}),/INVALID/);
 assert.throws(()=>store.recordCompleted({workspaceId:"ok",operationId:"x",evidenceSha256:"bad"}),/INVALID/);
 const path=store.path;
 if(process.platform!=="win32") assert.equal(statSync(path).mode & 0o777,0o600);
 const readonly = new Database(path,{readonly:true,fileMustExist:true});
 assert.throws(()=>readonly.prepare("DELETE FROM coach_review_events").run(),/readonly/);
 readonly.close();
 store.close();
 const restored=new CoachReviewEventStore(state);
 assert.equal(restored.listPending("ws-b").events[0]?.operation_id,"codex-1");
 restored.close();
 const malicious=join(root,"symlink-state");
 mkdirSync(malicious);
 symlinkSync(path,join(malicious,"coach-review-events.sqlite"));
 assert.throws(()=>new CoachReviewEventStore(malicious),/UNSAFE/);
 console.log("COACH006A3_NATIVE_EVENT_STORE_PASS");
} finally {rmSync(root,{recursive:true,force:true});}
